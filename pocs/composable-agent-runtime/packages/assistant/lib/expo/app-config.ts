import { access, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { parse as parseYaml } from 'yaml'
import { isObject } from '../packaging/addon-inventory.ts'
import {
  capabilityNames,
  resolveCapability,
  type ResolvedCapability
} from './capabilities.ts'
import {
  ASSISTANT_INFERENCE_ACCELERATORS,
  type AssistantAccelerator,
  type AssistantAppConfig,
  type ResolvedAssistantAppConfig
} from './types.ts'

/**
 * The one file an application author writes. Assistant resolves it and hands
 * each composed package the shape that package already understands.
 */
export const ASSISTANT_CONFIG_FILENAMES = Object.freeze([
  'qvac.assistant.yaml',
  'qvac.assistant.yml'
] as const)

/** Written by Assistant; the SDK Expo plugin reads only this filename form. */
export const GENERATED_SDK_CONFIG_FILENAME = 'qvac.config.json'

/**
 * Config filenames the SDK Expo plugin prefers over the JSON file Assistant
 * generates. A project carrying one of these has two sources of truth.
 */
export const CONFLICTING_SDK_CONFIG_FILENAMES = Object.freeze([
  'qvac.config.ts',
  'qvac.config.mjs',
  'qvac.config.js'
] as const)

export const GENERATED_SDK_CONFIG_MARKER =
  'Generated by @qvac/assistant/expo-plugin from qvac.assistant.yaml. Do not edit.'

const LOG_LEVELS = Object.freeze(['error', 'warn', 'info', 'debug', 'off'] as const)
const SUPPORTED_CONFIG_VERSION = 1
const TOP_LEVEL_KEYS = Object.freeze(['version', 'logging', 'inference'] as const)
const LOGGING_KEYS = Object.freeze(['level'] as const)
const INFERENCE_KEYS = Object.freeze([
  'capabilities',
  'accelerators',
  'bareRuntimeVersion'
] as const)

export async function findAssistantConfigFile(projectRoot: string) {
  const present: string[] = []
  for (const filename of ASSISTANT_CONFIG_FILENAMES) {
    const candidate = path.join(projectRoot, filename)
    try {
      await access(candidate)
      present.push(candidate)
    } catch {
      continue
    }
  }
  if (present.length > 1) {
    throw new Error(
      `Multiple assistant config files in ${projectRoot}: ` +
        `${present.map((entry) => path.basename(entry)).join(', ')}. Keep exactly one.`
    )
  }
  return present[0] ?? null
}

/**
 * Resolves the application's Assistant config. Returns `null` when the project
 * has no config file, which leaves every composed package on its own defaults —
 * the behaviour of a project that predates this file.
 */
export async function resolveAssistantAppConfig(
  projectRoot: string
): Promise<ResolvedAssistantAppConfig | null> {
  const configPath = await findAssistantConfigFile(projectRoot)
  if (configPath === null) return null
  const source = await readFile(configPath, 'utf8')
  const parsed = parseAssistantConfig(source, configPath)
  const capabilities = parsed.inference?.capabilities ?? null

  return {
    configPath,
    capabilities: capabilities === null ? null : capabilities.map((entry) => entry.capability),
    plugins: capabilities === null ? null : capabilities.map((entry) => entry.specifier),
    accelerators: parsed.inference?.accelerators ?? null,
    ...(parsed.logging?.level ? { loggerLevel: parsed.logging.level } : {}),
    ...(parsed.inference?.bareRuntimeVersion
      ? { bareRuntimeVersion: parsed.inference.bareRuntimeVersion }
      : {})
  }
}

/**
 * Propagates the resolved config into the only channel the SDK Expo plugin
 * reads: a `qvac.config.json` beside the app config. The SDK plugin accepts no
 * props, so this file is the seam between the two packages.
 */
export async function writeGeneratedSdkConfig(
  projectRoot: string,
  resolved: ResolvedAssistantAppConfig
) {
  const targetPath = path.join(projectRoot, GENERATED_SDK_CONFIG_FILENAME)
  await assertNoConflictingSdkConfig(projectRoot, resolved.configPath)
  await assertGeneratedOrAbsent(targetPath, resolved.configPath)

  const generated = {
    '//': GENERATED_SDK_CONFIG_MARKER,
    ...(resolved.plugins === null ? {} : { plugins: [...resolved.plugins] }),
    ...(resolved.loggerLevel === undefined ? {} : { loggerLevel: resolved.loggerLevel }),
    ...(resolved.bareRuntimeVersion === undefined
      ? {}
      : { bareRuntimeVersion: resolved.bareRuntimeVersion })
  }
  await writeFile(targetPath, `${JSON.stringify(generated, null, 2)}\n`)
  return targetPath
}

async function assertNoConflictingSdkConfig(projectRoot: string, configPath: string) {
  for (const filename of CONFLICTING_SDK_CONFIG_FILENAMES) {
    try {
      await access(path.join(projectRoot, filename))
    } catch {
      continue
    }
    throw new Error(
      `Conflicting SDK configuration: ${filename} takes precedence over the ` +
        `${GENERATED_SDK_CONFIG_FILENAME} generated from ${path.basename(configPath)}. ` +
        `Remove ${filename} and declare inference capabilities in ${path.basename(configPath)}.`
    )
  }
}

async function assertGeneratedOrAbsent(targetPath: string, configPath: string) {
  let source: string
  try {
    source = await readFile(targetPath, 'utf8')
  } catch {
    return
  }
  // A hand-written file is the case most likely to be malformed, so a parse
  // failure has to name the file and say what to do rather than surfacing a
  // bare SyntaxError from the middle of a prebuild.
  let parsed: unknown
  try {
    parsed = JSON.parse(source)
  } catch (cause) {
    const message = cause instanceof Error ? cause.message : String(cause)
    throw new Error(
      `Refusing to overwrite unparseable ${GENERATED_SDK_CONFIG_FILENAME} at ${targetPath}: ` +
        `${message}. Assistant generates this file from ${path.basename(configPath)}; ` +
        'delete it, or fix its JSON if it was hand-written.'
    )
  }
  if (isObject(parsed) && parsed['//'] === GENERATED_SDK_CONFIG_MARKER) return
  throw new Error(
    `Refusing to overwrite hand-written ${GENERATED_SDK_CONFIG_FILENAME} at ${targetPath}. ` +
      `Move its settings into ${path.basename(configPath)} and delete the file.`
  )
}

export function parseAssistantConfig(source: string, configPath: string): AssistantAppConfig {
  let document: unknown
  try {
    document = parseYaml(source)
  } catch (cause) {
    const message = cause instanceof Error ? cause.message : String(cause)
    throw new Error(`Malformed assistant config YAML at ${configPath}: ${message}`)
  }
  if (!isObject(document)) {
    throw new Error(`Assistant config must be a mapping: ${configPath}`)
  }
  assertKnownKeys(document, TOP_LEVEL_KEYS, configPath, 'assistant config')
  if (document.version !== SUPPORTED_CONFIG_VERSION) {
    throw new Error(
      `Unsupported assistant config version at ${configPath}: ` +
        `expected ${SUPPORTED_CONFIG_VERSION}, got ${JSON.stringify(document.version)}`
    )
  }

  return {
    version: SUPPORTED_CONFIG_VERSION,
    ...parseLogging(document.logging, configPath),
    ...parseInference(document.inference, configPath)
  }
}

function parseLogging(value: unknown, configPath: string) {
  if (value === undefined || value === null) return {}
  if (!isObject(value)) throw new Error(`logging must be a mapping: ${configPath}`)
  assertKnownKeys(value, LOGGING_KEYS, configPath, 'logging')
  const level = value.level
  if (level === undefined || level === null) return {}
  if (typeof level !== 'string' || !isLogLevel(level)) {
    throw new Error(
      `logging.level must be one of ${LOG_LEVELS.join(', ')} at ${configPath}, ` +
        `got ${JSON.stringify(level)}`
    )
  }
  return { logging: { level } }
}

function parseInference(value: unknown, configPath: string) {
  if (value === undefined || value === null) return {}
  if (!isObject(value)) throw new Error(`inference must be a mapping: ${configPath}`)
  assertKnownKeys(value, INFERENCE_KEYS, configPath, 'inference')

  const bareRuntimeVersion = value.bareRuntimeVersion
  if (
    bareRuntimeVersion !== undefined &&
    bareRuntimeVersion !== null &&
    (typeof bareRuntimeVersion !== 'string' || bareRuntimeVersion.length === 0)
  ) {
    throw new Error(`inference.bareRuntimeVersion must be a non-empty string: ${configPath}`)
  }

  const accelerators = parseAccelerators(value.accelerators, configPath)
  return {
    inference: {
      capabilities: parseCapabilities(value.capabilities, configPath),
      ...(accelerators === null ? {} : { accelerators }),
      ...(typeof bareRuntimeVersion === 'string' ? { bareRuntimeVersion } : {})
    }
  }
}

/**
 * `null` means the app said nothing and keeps every backend its addons ship.
 * An empty list is a deliberate CPU-only build, so it is not the same as
 * absence and must not be normalized into it.
 */
function parseAccelerators(value: unknown, configPath: string) {
  if (value === undefined || value === null) return null
  if (!Array.isArray(value)) {
    throw new Error(`inference.accelerators must be a list: ${configPath}`)
  }

  const selected: AssistantAccelerator[] = []
  for (const entry of value) {
    if (typeof entry !== 'string' || !isAccelerator(entry)) {
      throw new Error(
        `Unknown inference accelerator ${JSON.stringify(entry)} at ${configPath}. ` +
          `Valid accelerators: ${ASSISTANT_INFERENCE_ACCELERATORS.join(', ')}`
      )
    }
    if (selected.includes(entry)) {
      throw new Error(`Duplicate inference accelerator ${entry} at ${configPath}`)
    }
    selected.push(entry)
  }
  return Object.freeze([...selected].sort())
}

/**
 * Names are resolved against the catalog derived from the installed SDK, so an
 * alias and its canonical name are the same selection and collide as a
 * duplicate rather than bundling one plugin twice.
 */
function parseCapabilities(value: unknown, configPath: string) {
  if (value === undefined || value === null) {
    throw new Error(
      `inference.capabilities is required when inference is declared at ${configPath}. ` +
        'Remove the inference section to keep every built-in capability.'
    )
  }
  if (!Array.isArray(value)) {
    throw new Error(`inference.capabilities must be a list: ${configPath}`)
  }
  if (value.length === 0) {
    throw new Error(
      `inference.capabilities must name at least one capability at ${configPath}. ` +
        'Remove the inference section to keep every built-in capability.'
    )
  }

  const selected: ResolvedCapability[] = []
  for (const entry of value) {
    const resolved = typeof entry === 'string' ? resolveCapability(entry) : null
    if (resolved === null) {
      throw new Error(
        `Unknown inference capability ${JSON.stringify(entry)} at ${configPath}. ` +
          `Valid capabilities: ${capabilityNames().join(', ')}. ` +
          'A third-party plugin is named by its specifier, as in my-plugin/plugin.'
      )
    }
    if (selected.some((existing) => existing.capability === resolved.capability)) {
      throw new Error(`Duplicate inference capability ${resolved.capability} at ${configPath}`)
    }
    selected.push(resolved)
  }
  return Object.freeze(
    [...selected].sort((left, right) => left.capability.localeCompare(right.capability))
  )
}

function assertKnownKeys(
  value: Record<string, unknown>,
  allowed: readonly string[],
  configPath: string,
  label: string
) {
  const unknown = Object.keys(value).filter((key) => !allowed.includes(key))
  if (unknown.length === 0) return
  throw new Error(
    `Unknown ${label} key ${unknown.map((key) => JSON.stringify(key)).join(', ')} ` +
      `at ${configPath}. Valid keys: ${allowed.join(', ')}`
  )
}

function isAccelerator(value: string): value is AssistantAccelerator {
  return (ASSISTANT_INFERENCE_ACCELERATORS as readonly string[]).includes(value)
}

function isLogLevel(value: string): value is (typeof LOG_LEVELS)[number] {
  return (LOG_LEVELS as readonly string[]).includes(value)
}
