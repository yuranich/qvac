import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import {
  ASSISTANT_INFERENCE_ACCELERATORS,
  type AssistantAccelerator
} from '../expo/types.ts'

export const ACCELERATOR_FILTER_SENTINEL = '// [QVAC-ASSISTANT-ACCELERATORS]'

/**
 * `bare-link` copies every `.so` in an addon's `prebuilds/<host>/<name>/`
 * sidecar directory and offers no per-file filter, so a build that needs one
 * inference addon still ships every ggml backend that addon was published
 * with. Assistant already owns the BareKit linker to pin its project root;
 * this appends a prune step to the same file for the backends the app did not
 * declare.
 */
export async function pinBareKitLinkerProjectRoot(
  projectRoot: string,
  accelerators: readonly AssistantAccelerator[] | null = null
) {
  const require = createRequire(path.join(projectRoot, 'package.json'))
  let packageJsonPath: string
  try {
    packageJsonPath = require.resolve('react-native-bare-kit/package.json')
  } catch {
    return
  }
  const packageRoot = path.dirname(packageJsonPath)
  for (const relativePath of ['android/link.mjs', 'ios/link.mjs']) {
    const linkerPath = path.join(packageRoot, relativePath)
    const source = await readFileStrict(linkerPath, `BareKit linker ${relativePath}`)
    const pattern = /^const projectRoot = .+$/m
    if (!pattern.test(source)) {
      throw new Error(`BareKit linker project-root declaration was not found: ${linkerPath}`)
    }
    const pinned = source.replace(pattern, `const projectRoot = ${JSON.stringify(projectRoot)}`)
    // Android only: bare-link copies loose `.so` files there, while the Apple
    // platform builds signed `.framework`s around `.dylib`s. Pruning a signed
    // framework is a different operation and is not attempted here, so an iOS
    // build still ships every backend.
    const filtered =
      relativePath === 'android/link.mjs'
        ? appendAcceleratorFilter(pinned, accelerators)
        : pinned
    await writeFile(linkerPath, filtered)
  }
}

function appendAcceleratorFilter(
  source: string,
  accelerators: readonly AssistantAccelerator[] | null
) {
  const stripped = removeExistingFilter(source)
  if (accelerators === null) return stripped
  const kept = accelerators.filter((entry) => entry !== 'cpu')
  const removable = ASSISTANT_INFERENCE_ACCELERATORS.filter(
    (entry) => entry !== 'cpu' && !kept.includes(entry)
  )
  return `${stripped}${renderAcceleratorFilter(removable, ['cpu', ...kept])}`
}

/**
 * Each prebuild rewrites the linker from SDK's template, but a rerun against
 * an already-patched file must not stack a second filter block.
 */
function removeExistingFilter(source: string) {
  const index = source.indexOf(ACCELERATOR_FILTER_SENTINEL)
  return index === -1 ? source : source.slice(0, index)
}

/**
 * Removes only backends the app could have declared and did not. An
 * unrecognised `-ggml-<something>.so` is left alone: a future backend must not
 * disappear from a build just because this list predates it.
 */
function renderAcceleratorFilter(
  removableAccelerators: readonly string[],
  keptAccelerators: readonly string[]
) {
  return `
${ACCELERATOR_FILTER_SENTINEL} Generated by @qvac/assistant/expo-plugin from
// qvac.assistant.yaml. The app declared which GPU backends it ships; ggml's
// CPU backend is its base and is always kept, as is any backend neither list
// names — a backend introduced after this build tooling is reported, not
// deleted.
const removableAccelerators = new Set(${JSON.stringify(removableAccelerators)})
const keptAccelerators = new Set(${JSON.stringify(keptAccelerators)})
const acceleratorPattern = /-ggml-([a-z0-9]+)(?:[-_.]|\\.so$)/
const unrecognisedBackends = new Set()

async function pruneUndeclaredAccelerators (directory) {
  let entries
  try {
    entries = await fs.promises.readdir(directory, { withFileTypes: true })
  } catch (err) {
    if (err.code === 'ENOENT') return
    throw err
  }
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      await pruneUndeclaredAccelerators(entryPath)
      continue
    }
    if (!entry.name.endsWith('.so')) continue
    const match = acceleratorPattern.exec(entry.name)
    if (!match) continue
    if (removableAccelerators.has(match[1])) {
      await fs.promises.rm(entryPath)
      console.log('[QVAC] Dropped undeclared ' + match[1] + ' backend', entry.name)
      continue
    }
    if (!keptAccelerators.has(match[1])) unrecognisedBackends.add(match[1])
  }
}

await pruneUndeclaredAccelerators(addonsDir)

if (unrecognisedBackends.size > 0) {
  console.log(
    '[QVAC] Kept unrecognised ggml backend(s): ' +
      [...unrecognisedBackends].sort().join(', ') +
      '. Declare them in qvac.assistant.yaml to control whether they ship.'
  )
}
`
}

async function readFileStrict(filePath: string, label: string) {
  try {
    return await readFile(filePath, 'utf8')
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    throw new Error(`Failed to read ${label} at ${filePath}: ${message}`)
  }
}
